// Packs the naked-eye stars of the Yale Bright Star Catalogue (Hoffleit and Warren, 5th revised
// edition, 1991; public domain, distributed by the CDS as VizieR V/50) into the small module the 3D
// home's night sky reads (assets/js/home-scene/star-catalogue.mjs).
//
//   curl.exe -o catalog.gz https://cdsarc.cds.unistra.fr/ftp/V/50/catalog.gz
//   node bin/build_star_catalogue.mjs path/to/catalog.gz
//
// Each star keeps its J2000 direction (equatorial unit vector, x toward the equinox, z toward the
// north celestial pole, three signed 16-bit components), its visual magnitude V and its B-V colour
// index, eight bytes in all, brightest first. Stars fainter than V = 5.6 are left out: from La Jolla's
// coastal suburbs the naked eye reaches about magnitude 5 overhead on the darkest nights (Bortle 6),
// and the extra half magnitude lets the faintest fade out instead of popping.
import fs from "node:fs";
import zlib from "node:zlib";
import path from "node:path";
import { fileURLToPath } from "node:url";

const LIMIT = 5.6;
const source = process.argv[2];
if (!source) throw new Error("usage: node bin/build_star_catalogue.mjs path/to/catalog[.gz]");
const raw = fs.readFileSync(source);
const text = (source.endsWith(".gz") ? zlib.gunzipSync(raw) : raw).toString("latin1");
const field = (line, from, to) => line.slice(from - 1, to).trim();
const stars = [];
for (const line of text.split(/\r?\n/)) {
  if (line.length < 114) continue;
  const v = field(line, 103, 107),
    rah = field(line, 76, 77);
  // Novae and extragalactic objects kept for the numbering have no J2000 position.
  if (!v || !rah) continue;
  const V = Number(v);
  if (!(V <= LIMIT)) continue;
  const ra = ((Number(rah) + Number(field(line, 78, 79)) / 60 + Number(field(line, 80, 83)) / 3600) * 15 * Math.PI) / 180,
    sign = field(line, 84, 84) === "-" ? -1 : 1,
    dec = (sign * (Number(field(line, 85, 86)) + Number(field(line, 87, 88)) / 60 + Number(field(line, 89, 90)) / 3600) * Math.PI) / 180,
    bv = field(line, 110, 114);
  stars.push({
    hr: Number(field(line, 1, 4)),
    name: field(line, 5, 14),
    V,
    // A handful of stars have no measured B-V; a G-type white keeps them neutral.
    bv: bv === "" ? 0.6 : Number(bv),
    x: Math.cos(dec) * Math.cos(ra),
    y: Math.cos(dec) * Math.sin(ra),
    z: Math.sin(dec),
  });
}
stars.sort((a, b) => a.V - b.V || a.hr - b.hr);
const bytes = new Uint8Array(stars.length * 8),
  view = new DataView(bytes.buffer);
const q16 = (value) => Math.max(-32767, Math.min(32767, Math.round(value * 32767)));
stars.forEach((star, i) => {
  view.setInt16(i * 8, q16(star.x), true);
  view.setInt16(i * 8 + 2, q16(star.y), true);
  view.setInt16(i * 8 + 4, q16(star.z), true);
  view.setUint8(i * 8 + 6, Math.max(0, Math.min(255, Math.round((star.V + 2) * 30))));
  view.setInt8(i * 8 + 7, Math.max(-127, Math.min(127, Math.round(star.bv * 60))));
});
const base64 = Buffer.from(bytes).toString("base64");
const lines = base64.match(/.{1,120}/g).map((chunk) => `  "${chunk}"`);
const module = `// Generated by bin/build_star_catalogue.mjs from the Yale Bright Star Catalogue, 5th revised edition
// (Hoffleit and Warren 1991; public domain; CDS VizieR V/50). Do not edit by hand.
// ${stars.length} stars to V = ${LIMIT}, brightest first, eight bytes each (little-endian): the J2000
// equatorial unit vector as three int16 / 32767, then (V + 2) * 30 as uint8 and (B - V) * 60 as int8.
export const STAR_COUNT = ${stars.length};
export const STAR_LIMIT = ${LIMIT};
export const STAR_DATA = [
${lines.join(",\n")},
].join("");
`;
const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.join(here, "..", "assets", "js", "home-scene", "star-catalogue.mjs");
fs.writeFileSync(target, module);
console.log(
  JSON.stringify({
    stars: stars.length,
    brightest: stars.slice(0, 5).map((s) => `${s.name || s.hr} ${s.V}`),
    bytes: bytes.length,
    moduleBytes: Buffer.byteLength(module),
    gzipBytes: zlib.gzipSync(module).length,
  })
);
